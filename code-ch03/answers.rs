//! Chapter 3 exercise prompts and solutions.

use crate::ecc::{
    parse_hex, EccError, FieldElement, Point, PointError, PrivateKey, S256Point, Signature,
};
use crate::helper::hash256;
use num_bigint::BigUint;

fn field_223(value: u64) -> Result<FieldElement, PointError> {
    Ok(FieldElement::new(value, 223)?)
}

fn point_223(x: u64, y: u64) -> Result<Point, PointError> {
    Point::new(
        Some(field_223(x)?),
        Some(field_223(y)?),
        field_223(0)?,
        field_223(7)?,
    )
}

/*
// tag::exercise1[]
==== Exercise 1

Evaluate whether these points are on the curve __y__^2^ = __x__^3^ + 7 over __F__~223~:

++++
<ul class="simplelist">
<li>(192,105), (17,56), (200,119), (1,193), (42,99)</li>
</ul>
++++
// end::exercise1[]
*/

// tag::answer1[]
/// Returns whether the Exercise 1 coordinates belong to the finite-field curve.
pub fn answer_1() -> [bool; 5] {
    [(192, 105), (17, 56), (200, 119), (1, 193), (42, 99)].map(|(x, y)| point_223(x, y).is_ok())
}
// end::answer1[]

/*
// tag::exercise2[]
==== Exercise 2

For the curve __y__^2^ = __x__^3^ + 7 over __F__~223~, find:

* (170,142) + (60,139)
* (47,71) + (17,56)
* (143,98) + (76,66)
// end::exercise2[]
*/

// tag::answer2[]
/// Returns the three Exercise 2 finite-field point-addition results.
pub fn answer_2() -> Result<[Point; 3], PointError> {
    Ok([
        point_223(170, 142)?.checked_add(&point_223(60, 139)?)?,
        point_223(47, 71)?.checked_add(&point_223(17, 56)?)?,
        point_223(143, 98)?.checked_add(&point_223(76, 66)?)?,
    ])
}
// end::answer2[]

/*
// tag::exercise3[]
==== Exercise 3

Extend the finite-field point tests to verify the additions from Exercise 2.
// end::exercise3[]
*/

// tag::answer3[]
/// Verifies the finite-field additions requested by Exercise 3.
pub fn answer_3() -> Result<bool, PointError> {
    let additions = [
        (192, 105, 17, 56, 170, 142),
        (47, 71, 117, 141, 60, 139),
        (143, 98, 76, 66, 47, 71),
    ];

    additions.into_iter().try_fold(true, |all_match, values| {
        let (x1, y1, x2, y2, x3, y3) = values;
        Ok(all_match && point_223(x1, y1)?.checked_add(&point_223(x2, y2)?)? == point_223(x3, y3)?)
    })
}
// end::answer3[]

