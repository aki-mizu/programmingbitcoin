// tag::answer6[]
/// Verifies the two Exercise 6 ECDSA signatures.
pub fn answer_6() -> Result<[bool; 2], EccError> {
    let point = S256Point::new(
        Some(parse_hex(
            "887387e452b8eacc4acfde10d9aaf7f6d9a0f975aabb10d006e4da568744d06c",
        )?),
        Some(parse_hex(
            "61de6d95231cd89026e286df3b6ae4a894a3378e393e93a0f45b666329a0ae34",
        )?),
    )?;
    let first = point.verify(
        &parse_hex("ec208baa0fc1c19f708a9ca96fdeff3ac3f230bb4a7ba4aede4942ad003c0f60")?,
        &Signature::new(
            parse_hex("ac8d1c87e51d0d441be8b3dd5b05c8795b48875dffe00b7ffcfac23010d3a395")?,
            parse_hex("68342ceff8935ededd102dd876ffd6ba72d6a427a3edb13d26eb0781cb423c4")?,
        ),
    )?;
    let second = point.verify(
        &parse_hex("7c076ff316692a3d7eb3c3bb0f8b1488cf72e1afcd929e29307032997a838a3d")?,
        &Signature::new(
            parse_hex("eff69ef2b1bd93a66ed5219add4fb51e11a840f404876325a1e8ffe0529a2c")?,
            parse_hex("c7207fee197d27c618aea621406f6bf5ef6fca38681d82b2f06fddbdce6feab6")?,
        ),
    )?;

    Ok([first, second])
}
// end::answer6[]

/*
// tag::exercise7[]
==== Exercise 7

Sign the message `Programming Bitcoin!` with the secret 12345.
// end::exercise7[]
*/

// tag::answer7[]
/// Signs the Exercise 7 message with deterministic ECDSA.
pub fn answer_7() -> Result<Signature, EccError> {
    let private_key = PrivateKey::new(BigUint::from(12_345_u16))?;
    let z = BigUint::from_bytes_be(&hash256(b"Programming Bitcoin!"));
    private_key.sign(&z)
}
// end::answer7[]

#[cfg(test)]
mod tests {
    use super::{answer_1, answer_2, answer_3, answer_4, answer_5, answer_6, answer_7};
    use crate::ecc::{parse_hex, S256Point};
    use crate::helper::hash256;
    use num_bigint::BigUint;

    #[test]
    fn solves_the_finite_field_exercises() {
        assert_eq!(answer_1(), [true, true, false, true, false]);
        assert_eq!(
            answer_2().unwrap()[0].to_string(),
            "Point(220,181)_0_7 FieldElement(223)"
        );
        assert!(answer_3().unwrap());
        let results = answer_4().unwrap();
        assert_eq!(results[0].to_string(), "Point(49,71)_0_7 FieldElement(223)");
        assert_eq!(
            results[1].to_string(),
            "Point(64,168)_0_7 FieldElement(223)"
        );
        assert_eq!(
            results[2].to_string(),
            "Point(36,111)_0_7 FieldElement(223)"
        );
        assert_eq!(
            results[3].to_string(),
            "Point(194,51)_0_7 FieldElement(223)"
        );
        assert_eq!(
            results[4].to_string(),
            "Point(116,55)_0_7 FieldElement(223)"
        );
        assert!(results[5].is_infinity());
        assert_eq!(answer_5().unwrap(), 7);
    }

    #[test]
    fn solves_the_signature_exercises() {
        assert_eq!(answer_6().unwrap(), [true, true]);

        let z = BigUint::from_bytes_be(&hash256(b"Programming Bitcoin!"));
        let key = S256Point::new(
            Some(
                parse_hex("f01d6b9018ab421dd410404cb869072065522bf85734008f105cf385a023a80f")
                    .unwrap(),
            ),
            Some(
                parse_hex("0eba29d0f0c5408ed681984dc525982abefccd9f7ff01dd26da4999cf3f6a295")
                    .unwrap(),
            ),
        )
        .unwrap();
        assert!(key.verify(&z, &answer_7().unwrap()).unwrap());
    }
}
