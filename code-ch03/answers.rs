/*
// tag::exercise5[]
==== Exercise 5

For the curve __y__^2^ = __x__^3^ + 7 over __F__~223~, find the order of the group generated by (15,86).
// end::exercise5[]
*/

// tag::answer5[]
/// Returns the order of the group generated by the Exercise 5 point.
pub fn answer_5() -> Result<usize, PointError> {
    let point = point_223(15, 86)?;
    let infinity = Point::infinity(field_223(0)?, field_223(7)?)?;
    let mut product = point.clone();
    let mut count = 1;

    while product != infinity {
        product = product.checked_add(&point)?;
        count += 1;
    }

    Ok(count)
}
// end::answer5[]

